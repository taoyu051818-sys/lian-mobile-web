#!/usr/bin/env node
/**
 * Auto-generates docs/architecture/auto/file-ownership.md from src/.
 *
 * The hand-maintained current-file-ownership.md table drifts whenever files
 * are added/renamed/deleted. This script regenerates a deterministic snapshot
 * of every src/ file, grouped by top-level domain, so the doc tracks reality.
 *
 * Run: node scripts/generate-ownership-doc.js [--check]
 *   --check exits 1 if the regenerated content differs from the file on disk.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "docs/architecture/auto/file-ownership.md");

const CODE_EXT = new Set([".ts", ".vue", ".css"]);

async function walk(dir) {
  const out = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(full)));
    else if (CODE_EXT.has(path.extname(e.name))) out.push(full);
  }
  return out;
}

function summarize(content, ext) {
  const lines = content.split(/\r?\n/);
  if (ext === ".vue") {
    // pick first non-empty comment in <script> or <template>, else first defineProps line
    for (const l of lines) {
      const trimmed = l.trim();
      if (trimmed.startsWith("//") && trimmed.length > 4) return trimmed.slice(2).trim();
    }
    return "Vue SFC";
  }
  if (ext === ".css") return "Stylesheet";
  // .ts: prefer leading JSDoc, else first export
  let inBlock = false;
  const block = [];
  for (const l of lines) {
    const t = l.trim();
    if (t.startsWith("/**")) {
      inBlock = true;
      continue;
    }
    if (inBlock) {
      if (t.startsWith("*/")) break;
      block.push(t.replace(/^\*\s?/, ""));
    }
  }
  const doc = block.join(" ").trim();
  if (doc) return doc.length > 120 ? doc.slice(0, 117) + "..." : doc;
  const exp = lines.find((l) =>
    /^export\s+(?:default\s+)?(?:function|class|const|interface|type)/.test(l),
  );
  if (exp) return exp.replace(/\s*\{?\s*$/, "").trim();
  return "TypeScript module";
}

function lineCount(content) {
  return content.split(/\r?\n/).length;
}

function group(rel) {
  const parts = rel.split(/[\\/]/);
  return parts[0] || "(root)";
}

async function main() {
  const files = await walk(SRC);
  files.sort();

  const groups = new Map();
  for (const abs of files) {
    const rel = path.relative(SRC, abs).replace(/\\/g, "/");
    const top = group(rel);
    const ext = path.extname(abs);
    const content = await fs.readFile(abs, "utf8");
    const summary = summarize(content, ext);
    const lines = lineCount(content);
    if (!groups.has(top)) groups.set(top, []);
    groups.get(top).push({ rel, summary, lines });
  }

  const sortedGroups = [...groups.keys()].sort();
  let md = `# File ownership (auto-generated)\n\n`;
  md += `Regenerated by \`node scripts/generate-ownership-doc.js\`. Do not edit by hand - every src/ file is listed below with a one-line summary and line count.\n\n`;
  md += `Total files: ${files.length}\n\n`;
  for (const g of sortedGroups) {
    const rows = groups.get(g);
    md += `## src/${g}/ (${rows.length} files)\n\n`;
    md += `| File | Summary | Lines |\n`;
    md += `| --- | --- | ---: |\n`;
    for (const r of rows) {
      const safe = r.summary.replace(/\|/g, "\\|");
      md += `| \`${r.rel}\` | ${safe} | ${r.lines} |\n`;
    }
    md += `\n`;
  }

  const prettier = await import("prettier");
  const prettierConfig = (await prettier.resolveConfig(OUT)) ?? {};
  md = await prettier.format(md, { ...prettierConfig, filepath: OUT });

  await fs.mkdir(path.dirname(OUT), { recursive: true });

  if (process.argv.includes("--check")) {
    let existing = "";
    try {
      existing = await fs.readFile(OUT, "utf8");
    } catch {
      /* file not present */
    }
    if (existing.replace(/\r\n/g, "\n") !== md) {
      console.error(
        `[ownership-doc] ${path.relative(ROOT, OUT)} is stale. Run: node scripts/generate-ownership-doc.js`,
      );
      process.exit(1);
    }
    return;
  }

  await fs.writeFile(OUT, md, "utf8");
  console.log(`[ownership-doc] wrote ${path.relative(ROOT, OUT)} (${files.length} files)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
